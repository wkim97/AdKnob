"""Convert demo_outputs.json (from system_ads/demo/generate_demo.py) into the page's demo data.

    python scripts/build_demo_data.py path/to/demo_outputs.json [tau_default]

Writes static/data/demo_data.js, which defines window.ADKNOB_DEMO. A JS file (rather than
JSON fetched at runtime) lets the page also work when opened directly from disk.
"""
import json
import os
import sys

import numpy as np

src = sys.argv[1]
# Default threshold shown in the demo (the paper's quantitative evaluation uses 0.005).
tau_default = float(sys.argv[2]) if len(sys.argv) > 2 else 0.008
dst = os.path.join(os.path.dirname(__file__), "..", "static", "data", "demo_data.js")

raw = json.load(open(src))
results = {}
scores = []
for key, entry in raw["results"].items():
    results[key] = {}
    for lv in ("1", "2", "3", "4"):
        if lv not in entry:
            continue
        spans = [{"start": s["start"], "end": s["end"], "score": round(s["score"], 6)}
                 for s in entry[lv]["spans"]]
        scores += [s["score"] for s in spans]
        results[key][lv] = {"response": entry[lv]["response"], "spans": spans}

# Threshold slider range (log scale) covering the bulk of the sentence scores.
lo = float(np.percentile(scores, 1)) if scores else 0.0005
hi = float(np.percentile(scores, 99.5)) if scores else 0.05
tau_range = [max(round(lo, 5), 1e-4), round(hi, 4)]

tau_range = [min(tau_range[0], tau_default / 2), max(tau_range[1], tau_default * 2)]
out = {"prompts": raw["prompts"], "ads": raw["ads"], "tau_default": tau_default,
       "tau_range": tau_range, "results": results}
with open(dst, "w") as f:
    f.write("// Generated by scripts/build_demo_data.py. Do not edit by hand.\n")
    f.write("window.ADKNOB_DEMO = ")
    json.dump(out, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")

n = sum(len(v) for v in results.values())
print(f"{len(results)} combinations, {n} responses, {len(scores)} sentences; "
      f"tau_default={tau_default}, tau_range={tau_range}; wrote {os.path.normpath(dst)} ({os.path.getsize(dst) / 1024:.0f} KB)")
